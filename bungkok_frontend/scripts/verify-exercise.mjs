import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { buildSession, evaluateChallenges } from '../src/utils/exercise.js';

const make = seconds => buildSession({ total: seconds, upright: seconds, forward: 0, backward: 0, unknown: 0, paused: 0, breaks: 1, reminders: 0 }, new Date(), {}, 'test');
assert.equal(make(299).pointsEarned, 0);
assert.equal(make(300).pointsEarned, 5);
assert.equal(make(1800).pointsEarned, 25);
const challenges = [{ id: 'tiga-hari', type: 'diikuti', current: 2, total: 3, rewardValue: '+15 poin' }];
const first = evaluateChallenges(challenges, make(1500));
assert.equal(first.bonus, 15);
assert.equal(evaluateChallenges(first.updated, make(1500)).bonus, 0);

const browser = await chromium.launch({ channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1024 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
try {
  await page.goto('http://127.0.0.1:5173/app/dashboard');
  await page.clock.install();
  await page.getByRole('button', { name: 'Mulai Latihan Sekarang', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Lanjut ke Kalibrasi' })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Gunakan simulasi tanpa kamera' }).click();
  await dialog.getByLabel('Pencahayaan ruangan memadai').check();
  await dialog.getByLabel('Bahu kiri dan kanan terlihat dalam bingkai').check();
  await dialog.screenshot({ path: 'design-reference/verification/exercise-setup.png' });
  await dialog.getByRole('button', { name: 'Lanjut ke Kalibrasi' }).click();
  await dialog.getByRole('button', { name: 'Mulai Kalibrasi' }).click();
  await page.clock.runFor(3100);
  await expect(dialog.getByText('✓ Kalibrasi Berhasil · 86°')).toBeVisible();
  await dialog.getByRole('button', { name: 'Atur Sesi Latihan' }).click();
  await dialog.getByLabel('Kecepatan demo').selectOption('60');
  await dialog.getByLabel('Suara pengingat').uncheck();
  await dialog.screenshot({ path: 'design-reference/verification/exercise-config.png' });
  await dialog.getByRole('button', { name: 'Mulai Latihan Sekarang', exact: true }).click();
  await page.clock.runFor(3000);
  assert.ok(Number((await dialog.locator('.exercise-timer').innerText()).split(':')[0]) >= 3);
  await dialog.getByLabel('Simulasikan postur').selectOption('forward');
  await page.clock.runFor(2000);
  await expect(dialog.locator('.exercise-timer')).toHaveText('00:00');
  await dialog.getByRole('button', { name: 'Ambil Jeda' }).click();
  await page.clock.runFor(1000);
  await dialog.getByRole('button', { name: 'Lanjutkan latihan' }).click();
  await dialog.getByLabel('Simulasikan postur').selectOption('upright');
  await dialog.screenshot({ path: 'design-reference/verification/exercise-active.png' });
  await page.clock.runFor(21000);
  await expect(dialog.getByRole('button', { name: 'Selesaikan Sesi', exact: true })).toBeVisible();
  await expect(dialog.getByText('+25 poin sesi', { exact: true })).toHaveCount(0);
  assert.ok(Number((await dialog.locator('.exercise-timer').innerText()).split(':')[0]) >= 21);
  await dialog.getByRole('button', { name: 'Tutup dialog' }).click();
  await expect(dialog.getByText('Akhiri sesi dan simpan hasil yang sudah tercatat?')).toBeVisible();
  await dialog.getByRole('button', { name: 'Ya, simpan hasil' }).click();
  await expect(dialog.getByText('+25 poin sesi', { exact: true })).toBeVisible();
  await expect(dialog.getByText(/185 → 225/)).toBeVisible();
  await expect(dialog.getByText(/Tiga Hari Mulai selesai/)).toBeVisible();
  await dialog.screenshot({ path: 'design-reference/verification/exercise-summary.png' });
  await dialog.getByRole('button', { name: 'Selesai & Kembali ke Dashboard' }).click();
  await expect(page.locator('.dashboard-stats')).toContainText('225');
  await expect(page.locator('.dashboard-level')).toContainText('210');
  assert.ok(parseFloat(await page.locator('.dashboard-total').innerText()) >= 26);
  await page.getByRole('link', { name: 'Riwayat Latihan', exact: true }).click();
  await expect(page.locator('tbody tr')).toHaveCount(7);
  assert.deepEqual(errors, []);
  console.log('PASS: free session continues beyond 25 minutes; upright streak resets and restarts; close requests manual finish; results, +25 session/+15 bonus and dashboard/history sync.');
} finally { await browser.close(); }
